    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
        try {
            double largo = Double.parseDouble(txtLargo.getText());
            double ancho = Double.parseDouble(txtAncho.getText());
            double cejaOriginal = Double.parseDouble(txtCeja.getText());
            String calibre = jComboBox1.getSelectedItem().toString();

            int reduccionCeja = reducciones.get(calibre)[0];
            int reduccionCuerpo = reducciones.get(calibre)[1];

            double cejaFinal = (cejaOriginal - reduccionCeja < 12) ? cejaOriginal : cejaOriginal - reduccionCeja;
            double cuerpo = ancho - 2 * cejaFinal - reduccionCuerpo;
            double desarrollo = 2 * cejaFinal + cuerpo;

            StringBuilder sb = new StringBuilder();
            sb.append("== DESARROLLO DE CHAROLA ==\n");
            sb.append("Largo: ").append(largo).append(" mm\n");
            sb.append("Ancho: ").append(ancho).append(" mm\n");
            sb.append("Calibre: ").append(calibre).append("\n");
            sb.append("Ceja original: ").append(cejaOriginal).append(" mm\n");
            sb.append("Reducción ceja: ").append(reduccionCeja).append(" mm\n");
            sb.append("Reducción cuerpo: ").append(reduccionCuerpo).append(" mm\n");
            sb.append("Ceja final: ").append(cejaFinal).append(" mm\n");
            sb.append("Cuerpo: ").append(cuerpo).append(" mm\n");
            sb.append("Desarrollo total: ").append(desarrollo).append(" mm\n");

            jTextArea1.setText(sb.toString());

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Por favor ingresa valores numéricos válidos.");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

