    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            if (jTextField1.getText().isEmpty() || jTextField2.getText().isEmpty() || jTextField3.getText().isEmpty()) {
                throw new IllegalArgumentException("Todos los campos deben estar completos.");
            }

            double largo = Double.parseDouble(jTextField1.getText());
            double ancho = Double.parseDouble(jTextField2.getText());
            double precioPorKilo = Double.parseDouble(jTextField3.getText());

            if (largo <= 0 || ancho <= 0 || precioPorKilo <= 0) {
                throw new IllegalArgumentException("Las medidas y el precio por kilo deben ser valores positivos.");
            }

            String calibre = (String) jComboBox1.getSelectedItem();
            double pesoTeorico;

            switch (calibre) {
                case "20": pesoTeorico = 0.0007229; break;
                case "18": pesoTeorico = 0.0009862; break;
                case "16": pesoTeorico = 0.0012335; break;
                case "14": pesoTeorico = 0.0015345; break;
                case "12": pesoTeorico = 0.0021580; break;
                case "10": pesoTeorico = 0.0027680; break;
                case "3/16": pesoTeorico = 0.0038430; break;
                case "1/4": pesoTeorico = 0.0051330; break;
                default: throw new IllegalArgumentException("Calibre no válido.");
            }

            double area = largo * ancho;
            double precio = area * pesoTeorico * precioPorKilo;

            JOptionPane.showMessageDialog(this, "El precio calculado es: $" + String.format("%.2f", precio));
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese valores numéricos válidos.", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

