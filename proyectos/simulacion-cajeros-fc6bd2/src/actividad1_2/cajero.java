    private void btnNuevoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNuevoActionPerformed
                                         
   if (btnNuevo.getText().equals("Nuevo")) {
                txtNumCajero.setText(lista.size() > 0 ? String.valueOf(lista.size() + 1) : "1");
                txtNumCajero.setEditable(false);
                txtNombre.setEnabled(true);
                txtApp.setEnabled(true);
                txtApm.setEnabled(true);
                txtFondoInicial.setEnabled(true);
                btnNuevo.setText("Guardar");
                btnBuscar.setEnabled(false);
                btnSalir.setText("Cancelar");
                txtNombre.requestFocus();
            } else if (btnNuevo.getText().equals("Guardar")) {
                if (txtNumCajero.getText().isEmpty() || txtNombre.getText().isEmpty() ||
                    txtApp.getText().isEmpty() || txtApm.getText().isEmpty() || txtFondoInicial.getText().isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Completa todos los campos", "BIH", JOptionPane.ERROR_MESSAGE);
                    return;
                }

                Cajeros caj = new Cajeros();
                try {
                    caj.setNumEmpleado(Integer.parseInt(txtNumCajero.getText()));
                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(this, "Número de cajero inválido", "BIH", JOptionPane.ERROR_MESSAGE);
                    return;
                }

                caj.setNombre(txtNombre.getText());
                caj.setApp(txtApp.getText());
                caj.setApm(txtApm.getText());

                try {
                    caj.setFondoInicial(Double.parseDouble(txtFondoInicial.getText()));
                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(this, "Fondo inicial inválido", "BIH", JOptionPane.ERROR_MESSAGE);
                    return;
                }

                lista.put(caj.getNumEmpleado(), caj);
                JOptionPane.showMessageDialog(this, "Cajero guardado correctamente");
                resetear();
            }

    }//GEN-LAST:event_btnNuevoActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
             if (btnBuscar.getText().equals("Buscar")) {
                if (!txtNumCajero.getText().isEmpty()) {
                    Cajeros tmp = (Cajeros) lista.get(Integer.valueOf(txtNumCajero.getText()));
                    if (tmp == null) {
                        JOptionPane.showMessageDialog(this, "El cajero no existe", "BIH", JOptionPane.ERROR_MESSAGE);
                        txtNumCajero.requestFocus();
                        return;
                    }

                    txtNombre.setText(tmp.getNombre());
                    txtApp.setText(tmp.getApp());
                    txtApm.setText(tmp.getApm());
                    txtFondoInicial.setText(String.valueOf(tmp.getFondoInicial()));

                    btnNuevo.setEnabled(false);
                    btnBuscar.setText("Modificar");
                    btnEliminar.setEnabled(true);
                    btnSalir.setText("Cancelar");
                    txtNumCajero.setEnabled(false);
                }
            }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
      int confirm = JOptionPane.showConfirmDialog(this, "¿Eliminar este cajero?", "Confirmar", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                lista.remove(Integer.valueOf(txtNumCajero.getText()));
                JOptionPane.showMessageDialog(this, "Cajero eliminado.");
                resetear();
            }
    }//GEN-LAST:event_btnEliminarActionPerformed

