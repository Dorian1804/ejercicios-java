    public Principal() {
        initComponents();
        arch=new File ("XML/clientes.xml");
        if (arch.exists())
        {   
            if (!arch.isFile())
            {
               JOptionPane.showMessageDialog(getMe(),"Error al abrir el archivo XML","Banco Internacional de Hyrule (BIH)",JOptionPane.ERROR_MESSAGE);
               this.dispose();
            }
        }
        else
        {
            try {
                arch.createNewFile();
            } catch (IOException ex) {
               JOptionPane.showMessageDialog(getMe(),"Error al abrir el archivo XML","Banco Internacional de Hyrule (BIH)",JOptionPane.ERROR_MESSAGE);
               this.dispose();
            }
        }
        clientesXML=new XML(arch);
       
        try {
            lista=clientesXML.leeXML();
            
        } catch (NullPointerException e) {
            this.dispose();
        }
      
                
        Toolkit tk=Toolkit.getDefaultToolkit();
        Dimension d=tk.getScreenSize();
        setSize (656, 650);
        setLocation((d.width-getSize().width)/2,(d.height-getSize().height)/2);
        setTitle("Banco Internacional de Hyrule (BIH)");
        setVisible(true);
    }

