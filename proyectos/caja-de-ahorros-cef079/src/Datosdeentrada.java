    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
    String idTitular = jTextFieldID.getText();
    String titular = jTextFieldTitular.getText();
    String domicilio = jTextFieldDomicilio.getText();
    String telefono = jTextFieldTelefono.getText();
    String saldoInicial = jTextFieldSaldo.getText();

        if (idTitular.isEmpty() || titular.isEmpty() || domicilio.isEmpty() || telefono.isEmpty() || saldoInicial.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Error", JOptionPane.ERROR_MESSAGE);
        } else {
            try {
                double saldo = Double.parseDouble(saldoInicial);
                JOptionPane.showMessageDialog(this, "Datos guardados correctamente:\nID Titular: " + idTitular +
                        "\nTitular: " + titular + "\nDomicilio: " + domicilio + "\nTeléfono: " + telefono + "\nSaldo inicial: " + saldo,
                        "Información", JOptionPane.INFORMATION_MESSAGE);
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "El saldo inicial debe ser un número válido.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

