    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
   // Mostrar mensaje de confirmación
    int response = JOptionPane.showConfirmDialog(this, 
        "¿Estás seguro de que deseas limpiar los datos?", 
        "Confirmación", 
        JOptionPane.YES_NO_OPTION, 
        JOptionPane.QUESTION_MESSAGE);
    
    // Si el usuario selecciona "Sí", limpiar los campos
    if (response == JOptionPane.YES_OPTION) {
        txtIdTitular.setText("");
        txtTitular.setText("");
        txtDomicilio.setText("");
        txtTelefono.setText("");
        txtSaldoInicial.setText("");

        // Opcional: Colocar el cursor en el primer campo
        txtIdTitular.requestFocus();
    }
    // Si el usuario selecciona "No", no hacer nada
    }//GEN-LAST:event_jButton2ActionPerformed

    private void btndepositarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndepositarActionPerformed
  String montoStr = JOptionPane.showInputDialog(this, "Ingrese el monto a depositar:", "Depositar", JOptionPane.PLAIN_MESSAGE);

    if (montoStr != null && !montoStr.isEmpty()) {
        try {
            double monto = Double.parseDouble(montoStr);
            if (monto > 0) {
                saldo += monto; // Actualizar saldo
                txtSaldoInicial.setText(String.format("%.2f", saldo)); // Reflejar el cambio en el campo de texto
                JOptionPane.showMessageDialog(this, "Depósito realizado con éxito. Saldo actual: $" + saldo, "Información", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "El monto debe ser positivo.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El monto debe ser un número válido.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    } else {
        JOptionPane.showMessageDialog(this, "Debe ingresar un monto.", "Advertencia", JOptionPane.WARNING_MESSAGE);
    }
    }//GEN-LAST:event_btndepositarActionPerformed

    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
   String montoStr = JOptionPane.showInputDialog(this, "Ingrese el monto a retirar:", "Retirar", JOptionPane.PLAIN_MESSAGE);

    if (montoStr != null && !montoStr.isEmpty()) {
        try {
            double monto = Double.parseDouble(montoStr);
            if (monto > 0 && monto <= saldo) {
                saldo -= monto; // Actualizar saldo
                txtSaldoInicial.setText(String.format("%.2f", saldo)); // Reflejar el cambio en el campo de texto
                JOptionPane.showMessageDialog(this, "Retiro realizado con éxito. Saldo actual: $" + saldo, "Información", JOptionPane.INFORMATION_MESSAGE);
            } else if (monto > saldo) {
                JOptionPane.showMessageDialog(this, "Saldo insuficiente.", "Error", JOptionPane.ERROR_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "El monto debe ser positivo.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El monto debe ser un número válido.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    } else {
        JOptionPane.showMessageDialog(this, "Debe ingresar un monto.", "Advertencia", JOptionPane.WARNING_MESSAGE);
    }
    }//GEN-LAST:event_jButton5ActionPerformed

