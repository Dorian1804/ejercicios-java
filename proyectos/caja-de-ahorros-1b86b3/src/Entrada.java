    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
    // Obtención de los datos desde los campos de texto
    String idTitular = txtIdTitular.getText();
    String titular = txtTitular.getText();
    String domicilio = txtDomicilio.getText();
    String telefono = txtTelefono.getText();
    String saldoInicial = txtSaldoInicial.getText();

    // Validación de campos vacíos
    if (idTitular.isEmpty() || titular.isEmpty() || domicilio.isEmpty() || telefono.isEmpty() || saldoInicial.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    try {
        // Conversión del saldo inicial a tipo numérico
        saldo = Double.parseDouble(saldoInicial); // Asignar saldo inicial a la variable global

        // Cálculo del saldo con un interés del 5%
        double saldoConInteres = saldo * 1.05;

        // Mensaje de confirmación con los datos ingresados
        JOptionPane.showMessageDialog(this, 
            "Datos guardados correctamente:\n" +
            "ID Titular: " + idTitular + "\n" +
            "Titular: " + titular + "\n" +
            "Domicilio: " + domicilio + "\n" +
            "Teléfono: " + telefono + "\n" +
            "Saldo inicial: $" + String.format("%.2f", saldo) + "\n" +
            "Con un interés del 5% anual, su saldo sería de: $" + String.format("%.2f", saldoConInteres), 
            "Información", JOptionPane.INFORMATION_MESSAGE);

    } catch (NumberFormatException e) {
        // Manejo de error si el saldo no es un número válido
        JOptionPane.showMessageDialog(this, "El saldo inicial debe ser un número válido.", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton3ActionPerformed

