    /**
     * @param args the command line arguments
     */
    
            private void procesarTexto() {
        String palabra = txtPalabra.getText().trim();
        if (!palabra.isEmpty()) {
            String resultado = String.join("-", palabra.split(""));
            JOptionPane.showMessageDialog(this, "Palabra separada: " + resultado, "Resultado", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese una palabra.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

